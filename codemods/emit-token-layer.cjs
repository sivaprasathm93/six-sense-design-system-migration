#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const { DEFAULTS } = require('./lib/config.cjs');
const { parseTokens } = require('./lib/color.cjs');
const { newlineOf, toRelativePath } = require('./lib/source.cjs');

/**
 * Emits the CSS custom-property layer the migration's `var(--color-*)`
 * references resolve against.
 *
 * Rewriting `#1a73e8` to `var(--color-blue-500)` is only safe if something
 * declares `--color-blue-500`. Nothing did, and an undefined custom property
 * makes the whole declaration invalid at computed-value time -- transparent
 * backgrounds, missing borders, dropped gradients. This generates that layer
 * from the same token file the codemod maps against, so the two cannot drift.
 *
 *   node codemods/emit-token-layer.cjs [--check]
 *
 * `--check` writes nothing and exits non-zero when the committed layer is out
 * of date, which is what CI runs.
 */

const HEADER = [
  '/*',
  ' * Generated by codemods/emit-token-layer.cjs from tokens/primitive-tokens.json.',
  ' * Do not edit by hand: run `npm run tokens:css` after changing the token file.',
  ' */',
];

/** @param {Map<string, string>} tokenMap normalized hex -> token name. */
function renderTokenLayer(tokenMap, newline = '\n') {
  const declarations = [...tokenMap]
    .map(([hex, name]) => `  --color-${name}: ${hex};`)
    .sort();
  return `${[...HEADER, ':root {', ...declarations, '}'].join(newline)}${newline}`;
}

function run(options, logger = console) {
  const tokenFile = path.resolve(options.root, options.tokens || DEFAULTS.tokens);
  const outputFile = path.resolve(options.root, options.output || DEFAULTS.tokenLayer);
  const existing = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : null;
  const contents = renderTokenLayer(parseTokens(tokenFile), existing ? newlineOf(existing) : '\n');
  const relative = toRelativePath(options.root, outputFile);

  if (options.check) {
    if (existing === contents) {
      logger.log(`Token layer is up to date: ${relative}`);
      return 0;
    }
    logger.error(`Token layer is out of date: ${relative}. Run \`npm run tokens:css\`.`);
    return 1;
  }

  if (existing === contents) {
    logger.log(`Token layer unchanged: ${relative}`);
    return 0;
  }
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, contents);
  logger.log(`Wrote ${relative}`);
  return 0;
}

function parseArgs(argv) {
  const options = { root: path.resolve(__dirname, '..'), check: false };
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    if (flag === '--check') options.check = true;
    else if (flag === '--root' || flag === '--tokens' || flag === '--output') {
      if (!argv[index + 1]) throw new Error(`Missing value after ${flag}`);
      const value = argv[++index];
      options[flag.slice(2)] = flag === '--root' ? path.resolve(value) : value;
    } else throw new Error(`Unknown option: ${flag}`);
  }
  return options;
}

if (require.main === module) {
  try {
    process.exitCode = run(parseArgs(process.argv.slice(2)));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { renderTokenLayer, run };
